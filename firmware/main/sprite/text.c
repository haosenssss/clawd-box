#define FONT_FIRST 0x20
#define FONT_LAST 0x7E

static void put_block(const text_canvas_t *c, int x, int y, int size, uint16_t color)
{
    for (int dy = 0; dy < size; dy++) {
        const int py = y + dy;
        if (py < 0 || py >= c->height) continue;
        uint16_t *line = c->pixels + (size_t)py * c->width;
        for (int dx = 0; dx < size; dx++) {
            const int px = x + dx;
            if (px < 0 || px >= c->width) continue;
            line[px] = color;
        }
    }
}

int text_width(const char *s, int scale)
{
    if (s == NULL) return 0;
    const int n = (int)strlen(s);
    if (n == 0) return 0;
    /* 末字符不占字距 */
    return n * TEXT_ADVANCE(scale) - scale;
}

int text_draw(const text_canvas_t *c, int x, int y, const char *s, int scale,
              uint16_t color)
{
    if (c == NULL || c->pixels == NULL || s == NULL || scale < 1) return x;

    for (const char *p = s; *p != '\0'; p++) {
        unsigned char ch = (unsigned char)*p;
        /* 非 ASCII（比如中文会话名）画成一个实心方块占位，而不是乱码 */
        if (ch < FONT_FIRST || ch > FONT_LAST) {
            if (ch >= 0x80) {
                put_block(c, x + scale, y + scale, 4 * scale, color);
                x += TEXT_ADVANCE(scale);
                /* UTF-8 续字节整体跳过，避免一个汉字画出三个方块 */
                while ((unsigned char)p[1] >= 0x80 && (unsigned char)p[1] < 0xC0) p++;
            }
            continue;
        }
        const uint8_t *glyph = FONT5X7[ch - FONT_FIRST];
        for (int col = 0; col < 5; col++) {
            const uint8_t bits = glyph[col];
            for (int row = 0; row < 7; row++) {
                if (bits & (1u << row)) {
                    put_block(c, x + col * scale, y + row * scale, scale, color);
                }
            }
        }
        x += TEXT_ADVANCE(scale);
    }
    return x;
}

void text_draw_center(const text_canvas_t *c, int cx, int y, const char *s, int scale,
                      uint16_t color)
{
    text_draw(c, cx - text_width(s, scale) / 2, y, s, scale, color);
}
